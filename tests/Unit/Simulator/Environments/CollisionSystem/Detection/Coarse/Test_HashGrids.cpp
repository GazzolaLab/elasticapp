  template <typename PS, typename IPS>
  struct SimulatorInterface {
    inline auto primitives() const -> PS& {
      gsl::not_null<PS*> ptr_to_collection(primitive_ptr);
      return *ptr_to_collection;
    }

    template <typename F>
    void for_each_primitive(F f) {
      elastica::collision::for_each(primitives(), std::move(f));
    }

    // copy-pasted
    template <typename Primitive>
    inline auto n_primitives() const noexcept -> std::size_t {
      using ::elastica::collision::get_collection;
      return cpp17::size(get_collection<Primitive>(primitives()));
    }

    inline auto n_primitives() const -> std::size_t {
      std::size_t number_primitives = 0UL;
      tmpl::for_each<typename PS::PrimitiveList>([&](auto p) {
        using Primitive = tmpl::type_from<decltype(p)>;
        number_primitives += n_primitives<Primitive>();
      });
      return number_primitives;
    }

    PS* primitive_ptr;
    IPS* imposed_ptr;
  };

