  // for this test alone, I don't want to overload it generally
  // can be of different strategies, don't discount
  template <typename L, typename Strat1, typename Strat2>
  bool operator==(elastica::ContactCache<L, Strat1> const& lhs,
                  elastica::ContactCache<L, Strat2> const& rhs) noexcept {
    constexpr std::size_t n_pairs = tmpl::size<L>::value;

    auto check_equality_ref = [](auto const& x, auto const& y) {
      return std::addressof(x.get()) == std::addressof(y.get());
    };

    auto check_equality_pair = [=](auto const& x, auto const& y) {
      return check_equality_ref(x.first, y.first) and
             check_equality_ref(x.second, y.second);
    };

    auto check_equality_vec = [=](auto const& first,
                                  auto const& second) -> bool {
      using std::begin;
      using std::end;

      return (elastica::size(first) == elastica::size(second)) and
             std::equal(begin(first), end(first), begin(second),
                        [=](auto& first_pair, auto& second_pair) -> bool {
                          return check_equality_pair(first_pair, second_pair);
                        });
    };

    bool start = true;
    auto reduce = [&](bool new_result) { start &= new_result; };

    index_apply<n_pairs>([&](auto... Is) {
      EXPAND_PACK_LEFT_TO_RIGHT(reduce(check_equality_vec(
          std::get<Is>(lhs.data()), std::get<Is>(rhs.data()))));
    });

    return start;

    // lhs.data(), rhs.data();
    // return std::addressof(lhs.get()) == std::addressof(rhs.get());
  }

