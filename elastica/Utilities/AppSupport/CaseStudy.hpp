/*!\brief Define a \elastica case study
 * \ingroup application_support
 *
 * \details
 * Helper macro for declaring a user-class as a case-study, which helps generate
 * binding code for standalone and python-based executables
 *
 * \usage
 * Define a case-study class as usual in the corresponding header file (for more
 * information, see the case study tutorials), and then use the macro to declare
 * a case study
 * \code
 * // MyCaseStudy.hpp
 * struct MyCaseStudy {
 *   // ...details...
 * };
 *
 *
 * // declare MyCaseStudy
 * ELASTICA_CASE_STUDY(MyCaseStudy);
 * \endcode
 */
#define ELASTICA_CASE_STUDY(m)

//******************************************************************************
/*!\brief Metafunction that defines the interface input type for a case-study
 * \ingroup application_support
 *
 * \details
 * The InputTypes template obtains the type of interface input types that
 * is generated by \elastica for automatic executable generation.
 *
 * \usage
 * The InputType has an intuitive usage. Given the user defined case-study
 * `MyCaseStudy`, to obtain the input we use
 * \code
 * using inputs = InputTypes<MyCaseStudy>;
 * \endcode
 *
 * \example
 * The idiomatic way of using InputTypes is in the `setup` function of a case
 * study as shown below
 * \code
 * // MyCaseStudy.hpp
 * struct MyCaseStudy {
 *     using This = MyCaseStudy;
 *
 *     void setup(InputTypes<This> const&){
 *      // ...details...
 *     };
 * };
 * \endcode
 *
 * \tparam CaseStudy A user defined case-study
 */
template <typename CaseStudy>
using InputTypes = tmpl::as_tagged_tuple<typename CaseStudy::Parameters>;
