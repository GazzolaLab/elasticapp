        //**********************************************************************
        /*!\brief Collide two rigid primitives using a hybrid GJK--EPA approach
         *
         * \details
         * For more information on hybrid GJK/EPA see page 166 in
         * "Collision Detection in Interactive 3D Environments" by Gino van den
         * Bergen.
         *
         */
        template <typename FirstPrimitive,   // Type of the first primitive
                  typename SecondPrimitive>  // Type of the second primitive
        bool do_hybrid_GJK_EPA_collide(FirstPrimitive& first,
                                       SecondPrimitive& second, Vec3& normal,
                                       Vec3& contact_point,
                                       real_t& penetration_depth) {
          GJK gjk;
          penetration_depth = gjk.doGJK<FirstPrimitive, SecondPrimitive>(
              first, second, normal, contact_point);
          if (penetration_depth > contact_threshold) {
            // not close enough create no contact
            return false;
          } else if (penetration_depth < 0.01 * contact_threshold) {
            // objects are quite close use GJKcontactTrashold +
            // EPAcontactTrashold to calc distance
            if (gjk.do_contact_threshold<FirstPrimitive, SecondPrimitive>(
                    first, second)) {
              // possible penetration
              EPA epa;
              return epa.do_contact_threshold<FirstPrimitive, SecondPrimitive>(
                  first, second, gjk, normal, contact_point, penetration_depth);
            }
          } else {
            // objects are close but separated use data calculated by GJK
            return true;
          }
          // never to be reached
          return false;
        }
        //**********************************************************************

        //**********************************************************************
        /*!\brief Collide two rigid primitives using GJK followed by EPA
         *
         * \details
         * If GJK detects a potential collision, we use the more accurate EPA
         * algorithm to calculate the distance of penetration based on the
         * simplex generated by GJK.
         */
        template <typename FirstPrimitive,   // Type of the first primitive
                  typename SecondPrimitive>  // Type of the second primitive
        bool do_GJK_EPA_collide(FirstPrimitive& first, SecondPrimitive& second,
                                Vec3& normal, Vec3& contact_point,
                                real_t& penetration_depth) {
          GJK gjk;
          if (gjk.do_contact_threshold<FirstPrimitive, SecondPrimitive>(
                  first, second)) {
            // possible penetration, so launch EPA to compute distance
            EPA epa;
            return epa.do_contact_threshold<FirstPrimitive, SecondPrimitive>(
                first, second, gjk, normal, contact_point, penetration_depth);
          }

          return false;
        }
        //**********************************************************************

        //**********************************************************************
        /*!\brief Contact generation between two arbitrary convex primitives
         * \ingroup fine_collision_detection
         *
         * \tparam FirstPrimitive Type of the first colliding primitive
         * \tparam SecondPrimitive Type of the second colliding primitive
         * \tparam CC Type of the contact vector
         *
         * \param f The first colliding primitive.
         * \param s The second colliding primitive.
         * \param contacts Contact container for the generated contacts.
         * \return void
         *
         * The collision between arbitrary convex primitives is handled
         * using the GJK algorithm to check for intersections and then using
         * the EPA algorithm to compute penetration depth, if large enough,
         * else falling back to GJK's distance algorithm.
         */
        template <typename FirstPrimitive, typename SecondPrimitive,
                  typename CC,
                  Requires<cpp17::conjunction_v<
                      decltype(is_convex_rigid<FirstPrimitive>()),
                      decltype(is_convex_rigid<SecondPrimitive>())>> = nullptr>
        static void do_collide(FirstPrimitive& f, SecondPrimitive& s,
                               CC& contacts) {
          // Default case, not marked noexcept because GJK and EPA can throw

          Vec3 normal;
          Vec3 contact_point;
          real_t penetration_depth;
          if (do_hybrid_GJK_EPA_collide<FirstPrimitive, SecondPrimitive>(
                  f, s, normal, contact_point, penetration_depth)) {
            // bodys possibly overlap
            // normal points form object2 (m) to object1 (b)
            contacts.add_vertex_face_contact(&f, &s, contact_point, normal,
                                             penetration_depth);
            using namespace ::elastica::logging;
            log<debug>([&](auto& log) {
              log << "      Contact created between "
                  << ::pretty_type::short_name<FirstPrimitive>() << " "
                  << f.getID() << " and "
                  << ::pretty_type::short_name<SecondPrimitive>() << " "
                  << s.getID() << " (dist=" << penetration_depth << ")";
            });
          }
        }
