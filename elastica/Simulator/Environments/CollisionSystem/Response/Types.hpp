      /*!\brief Contact response solver based on Discrete Element Method (DEM)
       * \ingroup collision_response
       *
       * \details
       * DEMSolver applies the discrete element method to compute forces and
       * torques on both colliding bodies. It does so by processing a sequence
       * of contacts (generated by fine-detection) and using a force model,
       * , defined as the `ForceModel` meta-variable in the `Config_`
       * configuration template parameter.
       *
       * \note
       * The force model needs to be copyable (when parallel execution is
       * desired). Users are responsible to ensure that the state within force
       * model is not bulky, as it may slow down processing significantly.
       *
       * \tparam Config_ Collision configuration trait
       */
      template <
          typename Config_, typename = void,
          typename =
              void>  // TODO : remove extra template parameters afterwar cleanup
      using DEMSolver =
          DEMSolverOp<Config_,
                      typename Config_::KernelExecutionPolicy::ExecutionPolicy>;
