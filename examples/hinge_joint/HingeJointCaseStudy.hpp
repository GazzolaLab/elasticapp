// global is fine since its a cpp file
using String = const char* const;
namespace ec = elastica::configuration;
using CosseratRod = ::elastica::cosserat_rod::CosseratRod;

struct HingeJointConfiguration {
  static inline auto make_simulator_configuration() {
    auto system_config =
        ec::make_systems_configuration<tmpl::list<CosseratRod>>(
            ec::make_blocking_policy(ec::RestrictSizeAcrossBlockTypes{50UL}),
            ec::make_iteration_policy(
                ec::iterate_across_system_types_in(ec::seq),
                ec::iterate_over_systems_in(ec::seq)));

    return ec::make_simulator_configuration(
        ec::DefaultDomainConfiguration{}, system_config,
        ec::DefaultParallelConfiguration{}, ec::DefaultForcingConfiguration{},
        ec::DefaultConstraintsConfiguration{},
        ec::DefaultConnectionsConfiguration{});
  }

  static inline auto make_simulator() {
    return elastica::make_simulator<::elastica::modules::Forcing,
                                    ::elastica::modules::Constraints,
                                    ::elastica::modules::Connections>(
        make_simulator_configuration());
  }

  static inline auto make_time_stepper() {
    using TimeStepper = ::elastica::timestepper::PositionVerlet;
    return TimeStepper{};
  }
};

struct HingeJointCaseStudy
    : public ::elastica::CaseStudyInterface<HingeJointCaseStudy> {
  using Configuration = HingeJointConfiguration;
  using This = HingeJointCaseStudy;

  static constexpr String help = {R"help(
Hinge joint test-case
---------------------

Runs an example of two rods connected by a hinge joint that allows for motion
only along a constrained plane.

we connect two Cosserat rods together using a
hinge joint like so, with a force at the tip

         * Force
          \
           \
            ============================= (x) =============================
                          Rod1         Hinge joint             Rod 2
   ^ z
   |
   |
   o — — —> y
  /
 /
x

No other forces (like gravity) are considered.

The hinge joint allows for relative rod rotations about only one plane
common to both the rods (in this case y-z plane), but prevents relative
displacements. That means Rod2 in this case always lies on the y-z plane, still
connected to Rod1. Initially the rods are aligned along the y-axis, and the same
force as the Spherical Joint case with a time-varying direction (but fixed
magnitude) acts along the x-z plane. The torque due to this force has components
in all directions, but the hinge joint counteracts all torques in the
x-direction (and all forces of course). Intuitively then, you would expect the
rod to move up and down in the constrained y-z plane (due to this sinusoidal
time-varying force), but this is NOT what should actually happen. In the plot
provided by our python script, please pay attention to the applied force, its
changes in direction and associated torques generated by the rod. From this
visualization, it becomes apparent that the rod undergoes a complicated motion,
eventually oscillating about an upright position (i.e. oriented along the z
axis).
)help"};

  struct n_elements {
    // unsigned integer parameter
    using type = std::size_t;
    // documentation
    static constexpr String help = {"Number of elements in the rod"};
    static type default_value() { return 10UL; }
  };

  struct radius {
    using type = ::elastica::real_t;
    static constexpr String help = {"Radius of the rod"};
    static type default_value() { return 0.007; }
  };

  struct length {
    using type = ::elastica::real_t;
    static constexpr String help = {"Length of the rod"};
    static type default_value() { return 0.2; }
  };

  struct dt {
    using type = ::elastica::real_t;
    static constexpr String help = {"Time step of simulation"};
    static type default_value() {
      return 1e-05;  // damn low
    }
  };

  using Parameters = tmpl::list<n_elements, radius, length, dt>;

  /* Required functions */
  void setup(InputTypes<This> const& input_parameters);
  void step();
  void run();

  HingeJointCaseStudy() = default;
  HingeJointCaseStudy(HingeJointCaseStudy&&) noexcept = default;

  decltype(Configuration::make_time_stepper()) time_stepper =
      Configuration::make_time_stepper();
  decltype(Configuration::make_simulator()) simulator =
      Configuration::make_simulator();
  using RodRef = decltype(simulator->get_invalid_ref<CosseratRod>());
  using RodRefs = std::vector<RodRef>;

  static constexpr std::size_t n_rod_pairs() { return 1UL; };

  RodRefs rod_refs{2 * n_rod_pairs(),
                   simulator->get_invalid_ref<CosseratRod>()};

  inline auto communicate_from(RodRef& ref) {
    auto rod = ref.get();
    return std::make_tuple(::elastica::position(rod),
                           ::elastica::velocity(rod));
  }
  inline auto communicate() {
    // we dont have CTAD :(
    using CT = decltype(communicate_from(rod_refs[0UL]));
    using RT = std::vector<CT>;
    RT return_list;
    return_list.reserve(rod_refs.size());
    std::transform(std::begin(rod_refs), std::end(rod_refs),
                   std::back_inserter(return_list), [this](RodRef& rod_it) {
                     return this->communicate_from(rod_it);
                   });
    return return_list;
  }
};

ELASTICA_REGISTER_CASE_STUDY(HingeJointCaseStudy);

#endif  // ELASTICA_HINGEJOINTCASESTUDY_HPP
